/**
 * Haiku에게 시키는 일.
 *
 * 기준: v2 제품정의 §6.2(우리가 Haiku에게 시키는 일 6개), §8 INV-04·INV-06.
 * 하네스 P5 할 일 2.
 *
 * ## Haiku는 결과 페이지를 만들지 않는다
 *
 * 결과 페이지를 만들 **프롬프트**를 쓴다. 이것을 시스템 프롬프트 첫 줄에 두는
 * 이유는, 모델이 자료를 보면 곧장 HTML을 쓰고 싶어 하기 때문이다. (INV-04)
 *
 * ## 사용자 메시지는 P3의 조립 결과다
 *
 * 자료·선택·요구·금지가 이미 한 장에 모여 있으므로 그것을 그대로 재료로 준다.
 * 여기서 자료를 다시 조립하면 P3과 두 벌이 되고, 한쪽만 고쳐지는 날이 온다.
 * Haiku가 하는 일은 그 초안을 **자료에 맞게 구체화**하는 것이다.
 */

import { OUTPUT_REQUIREMENTS, PROHIBITIONS } from '../../domain/prompt.rules.ts';

function bulleted(items: readonly string[]): string {
  return items.map((item) => `- ${item}`).join('\n');
}

/**
 * 시스템 프롬프트. 제품정의 §6.2의 여섯 항목을 그대로 옮긴다.
 *
 * 순수 함수다. 시각도 난수도 넣지 않는다 - 같은 입력에서 같은 요청이 나가야
 * 캐시와 재현이 가능하다.
 */
export function buildSystemPrompt(): string {
  return [
    '너는 한 페이지짜리 HTML 문서를 만들 **프롬프트를 쓰는 사람**이다.',
    '문서 자체를 만들지 않는다. HTML을 출력하지 않는다.',
    '',
    '사용자가 규칙 기반으로 조립한 초안을 준다. 너는 그 초안을 자료에 맞게 다시 써서,',
    '다른 AI에게 그대로 붙여넣을 수 있는 프롬프트 한 장으로 만든다.',
    '',
    '## 지켜야 할 것',
    '',
    '1. 붙여넣은 자료에서 **실제로 근거가 있는 내용만** 쓴다. 없는 사실을 만들지 않는다.',
    '2. 고른 요소마다 "무엇을 담을지"를 자료에서 뽑아 구체적으로 지정한다.',
    '   "다이어그램을 그려라"가 아니라 "A와 B의 의존 관계를 다이어그램으로 그려라"까지 간다.',
    '3. 디자인 축을 **CSS로 옮길 수 있는 수준**으로 서술한다. 색상 역할, 간격 스케일,',
    '   폰트 스택을 말로 남긴다.',
    '4. 아래 금지 목록을 결과 프롬프트에 **그대로 싣는다.** 요약하거나 줄이지 않는다.',
    '5. 아래 결과물 요구사항을 결과 프롬프트에 싣는다.',
    '6. 한 페이지 분량을 넘기지 않게 범위를 좁힌다. 자료가 길면 무엇을 덜어 낼지 정해 준다.',
    '',
    '## 결과 프롬프트에 반드시 실을 금지 목록',
    '',
    bulleted(PROHIBITIONS),
    '',
    '## 결과 프롬프트에 반드시 실을 요구사항',
    '',
    bulleted(OUTPUT_REQUIREMENTS),
    '',
    '## 출력 형식',
    '',
    '완성된 프롬프트 전문만 출력한다. 설명, 머리말, "여기 있습니다" 같은 말을 붙이지 않는다.',
    '자료 원문은 결과 프롬프트 안에 그대로 인용해 남긴다.',
  ].join('\n');
}

/** 사용자 메시지. P3이 조립한 초안을 재료로 준다. */
export function buildUserMessage(templatePrompt: string): string {
  return [
    '아래는 규칙 기반으로 조립한 초안이다. 자료를 읽고, 각 요소가 자료의 무엇을 담을지',
    '구체적으로 지정해 다시 써라. 금지 목록과 요구사항은 그대로 남긴다.',
    '',
    '---',
    '',
    templatePrompt,
  ].join('\n');
}
